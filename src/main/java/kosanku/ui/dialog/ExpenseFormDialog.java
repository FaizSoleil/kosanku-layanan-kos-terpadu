    public ExpenseFormDialog(java.awt.Frame parent, boolean modal, ExpenseDialogMode mode, Expense beingEditedExpense) {
        super(parent, modal);
        this.mode = mode;
        this.beingEditedExpense = beingEditedExpense;
        initComponents();
        setTitle(mode == ExpenseDialogMode.ADD ? "Tambah Pengeluaran" : "Edit Pengeluaran");
        resetDialog();
        setLocationRelativeTo(null);
    }

    private void resetDialog() {
        saved = false;
        fieldDesc.setText("");
        fieldTotal.setText("");
        labelTitle.setText((mode == ExpenseDialogMode.ADD) ? "TAMBAH PENGELUARAN" : "EDIT PENGELUARAN  ");
        if (this.mode == ExpenseDialogMode.EDIT) {
            editSetup(beingEditedExpense.getExpenseDate(), beingEditedExpense.getDeskripsi(), beingEditedExpense.getJumlah()); 
            btnMain.setText("Simpan");
        } else {
            btnMain.setText("Tambah");
        }
    }

    private void editSetup(Date date, String desc, Double total) {
        LocalDate localDate = Instant.ofEpochMilli(date.getTime()).atZone(ZoneId.systemDefault()).toLocalDate();
        datePicker.setDate(localDate);
        fieldDesc.setText(desc);
        fieldTotal.setText(total.toString());
    }

    public boolean isSaved() { return saved; }
    public String getSavedDate() { return savedDate; }
    public String getSavedCategory() { return savedCategory; }
    public String getSavedTotal() { return savedTotal; }
    public void setMode(ExpenseDialogMode mode) { this.mode = mode; }

    public void save() {
        saved = true;
        saveData();
    }

    public void saveData() {
        java.time.LocalDate pickedDate = datePicker.getDate();
        savedDate = (pickedDate != null) ? pickedDate.toString() : "";
        savedCategory = fieldDesc.getText();
        savedTotal = fieldTotal.getText();
    }

